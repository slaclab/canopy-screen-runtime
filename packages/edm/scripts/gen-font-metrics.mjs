#!/usr/bin/env node
// Generate src/config/xFontMetrics.generated.ts: the X11 bitmap font metrics EDM
// actually draws with (ascent, descent, per-glyph advance widths), keyed by EDM
// font tag ("helvetica-bold-r-12.0").
//
// EDM positions every string with XTextWidth() and the font's ascent/descent
// (edmlib/utility.cc XDrawStringsAligned, getStringBoxSize). With these numbers
// the renderer places each glyph at EDM's pixel position; only the glyph shapes
// come from the web font.
//
// Input: `xlsfonts -lll` output for every XLFD of the site fonts.list, each
// block preceded by a "### SPEC <xlfd pattern>" line, e.g. from the fidelity
// harness's EDM image (Adobe 75/100 dpi fonts, the XLFDs fonts.list names):
//
//   docker exec <edm container> sh -c 'export DISPLAY=:100;
//     tail -n +4 /edmfiles/fonts.list | while IFS= read -r spec; do
//       [ -z "$spec" ] && continue; echo "### SPEC $spec";
//       xlsfonts -lll -fn "$spec" 2>&1 | head -400; done' > xlsfonts.txt
//   node scripts/gen-font-metrics.mjs xlsfonts.txt > src/config/xFontMetrics.generated.ts
//
// Tag naming follows edmlib/font_pkg.cc fontInfoClass::resolveFont: the first
// font XListFonts returns for the pattern, as family-weight-slant-size with
// slant "r" or "i" and size = POINT_SIZE/10 printed "%-.1f". The first entry
// for a tag wins (fonts.list has duplicates). Patterns the X server cannot
// match (Utopia is absent from the image) are skipped: EDM cannot load them
// either and falls back.
import { readFileSync } from 'node:fs';

const text = readFileSync(process.argv[2], 'utf8');
const fonts = new Map();
let cur = null;

function finish() {
  if (!cur || !cur.name) return;
  const f = cur.name.replace(/^-/, '').split('-');
  // foundry family weight slant setwidth addstyle pixel point resx resy spacing avgw reg enc
  const [, family, weight, slant, , , pixel, point] = f;
  const tag = `${family}-${weight}-${slant === 'r' ? 'r' : 'i'}-${(Number(point) / 10).toFixed(1)}`;
  if (fonts.has(tag)) return;
  // XTextWidth: a glyph the font lacks takes the default char's metrics, or
  // width 0 when the default char is missing too (Xlib TextExt.c CI_GET_*).
  const def = cur.widths.get(cur.defaultChar);
  const widths = [];
  for (let c = 0; c < 256; c++) widths.push(cur.widths.get(c) ?? def ?? 0);
  fonts.set(tag, {
    xlfd: cur.name,
    pixel: Number(pixel),
    ascent: cur.ascent,
    descent: cur.descent,
    maxAscent: cur.maxAscent ?? cur.ascent,
    maxDescent: cur.maxDescent ?? cur.descent,
    capHeight: cur.props.CAP_HEIGHT ?? null,
    xHeight: cur.props.X_HEIGHT ?? null,
    widths,
  });
}

for (const line of text.split('\n')) {
  if (line.startsWith('### SPEC')) {
    finish();
    cur = { name: null, widths: new Map(), props: {}, ascent: 0, descent: 0, defaultChar: 0 };
    continue;
  }
  if (!cur) continue;
  let m;
  if ((m = /^name:\s+(\S.*)$/.exec(line))) {
    // xlsfonts lists every match; only the first is what XListFonts(…, 1) gives EDM.
    if (cur.name) cur.done = true;
    else cur.name = m[1].trim();
  } else if (cur.done) {
    continue;
  } else if ((m = /^\s+ascent:\s+(-?\d+)/.exec(line))) cur.ascent = Number(m[1]);
  else if ((m = /^\s+descent:\s+(-?\d+)/.exec(line))) cur.descent = Number(m[1]);
  else if ((m = /^\s+default char:\s+0x([0-9a-f]+)/i.exec(line)))
    cur.defaultChar = parseInt(m[1], 16);
  else if ((m = /^\s+(CAP_HEIGHT|X_HEIGHT)\s+(\d+)/.exec(line))) cur.props[m[1]] = Number(m[2]);
  else if ((m = /^\s+max\s+(-?\d+)\s+(-?\d+)\s+(-?\d+)\s+(-?\d+)\s+(-?\d+)/.exec(line))) {
    // max_bounds: Motif lays text out with these (XmTextField baseline, preferred height).
    cur.maxAscent = Number(m[4]);
    cur.maxDescent = Number(m[5]);
  } else if ((m = /^\s+0x([0-9a-f]{4}) \(\d+\)\s+(-?\d+)/i.exec(line))) {
    cur.widths.set(parseInt(m[1], 16), Number(m[2]));
  }
}
finish();

const out = [];
out.push('// Generated by scripts/gen-font-metrics.mjs from `xlsfonts -lll` of the X11');
out.push('// fonts the site fonts.list names (Adobe 75 dpi bitmaps). Do not edit.');
out.push('//');
out.push('// Font metrics of the X11 Adobe bitmap fonts: Copyright (c) 1984, 1987 Adobe Systems');
out.push('// Incorporated; Copyright (c) 1988, 1991 Digital Equipment Corporation. Redistributed');
out.push('// under the permission notice of the X11 font distribution (xfonts-75dpi).');
out.push('//');
out.push('// widths: advance width of chars 0..255 (XTextWidth, default-char rule applied),');
out.push('// comma-separated to keep the module small.');
out.push('');
out.push("import type { XFontMetricsRaw } from './fonts.js';");
out.push('');
out.push('export const X_FONT_METRICS: Readonly<Record<string, XFontMetricsRaw>> = {');
for (const [tag, v] of [...fonts.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  out.push(
    `  ${JSON.stringify(tag)}: { xlfd: ${JSON.stringify(v.xlfd)}, pixel: ${v.pixel}, ascent: ${v.ascent}, ` +
      `descent: ${v.descent}, maxAscent: ${v.maxAscent}, maxDescent: ${v.maxDescent}, capHeight: ${v.capHeight}, xHeight: ${v.xHeight}, ` +
      `widths: ${JSON.stringify(v.widths.join(','))} },`
  );
}
out.push('};');
out.push('');
process.stdout.write(out.join('\n'));
process.stderr.write(`${fonts.size} font tags\n`);
